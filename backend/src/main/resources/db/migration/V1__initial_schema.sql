-- V1: initial data model for W1-W5. See docs/data-model.md for the business rules.
-- Conventions: BIGINT identity ids, TIMESTAMPTZ timestamps, enums as VARCHAR + CHECK,
-- named constraints (pk_/fk_/uq_/ux_/ck_/ix_) so violations are easy to map to errors.

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(150) NOT NULL,
    global_role   VARCHAR(20)  NOT NULL DEFAULT 'STUDENT',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT ck_users_global_role CHECK (global_role IN ('STUDENT', 'ADMIN'))
);
-- Email is unique case-insensitively (Ana@ubb.ro == ana@ubb.ro).
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));

-- ---------------------------------------------------------------------------
-- organizations
-- ---------------------------------------------------------------------------
CREATE TABLE organizations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(150) NOT NULL,
    description   TEXT,
    contact_email VARCHAR(255),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_organizations PRIMARY KEY (id)
);
CREATE UNIQUE INDEX ux_organizations_name_lower ON organizations (lower(name));

-- ---------------------------------------------------------------------------
-- organization_memberships (user <-> organization with an org-level role)
-- ---------------------------------------------------------------------------
CREATE TABLE organization_memberships (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT      NOT NULL,
    organization_id BIGINT      NOT NULL,
    org_role        VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    joined_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_organization_memberships PRIMARY KEY (id),
    CONSTRAINT fk_memberships_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_memberships_organization FOREIGN KEY (organization_id)
        REFERENCES organizations (id) ON DELETE RESTRICT,
    CONSTRAINT uq_memberships_user_organization UNIQUE (user_id, organization_id),
    CONSTRAINT ck_memberships_org_role CHECK (org_role IN ('PRESIDENT', 'ORGANIZER', 'MEMBER'))
);
-- (user_id, organization_id) is covered by the unique constraint; add the reverse lookup.
CREATE INDEX ix_memberships_organization_id ON organization_memberships (organization_id);

-- ---------------------------------------------------------------------------
-- events
-- ---------------------------------------------------------------------------
CREATE TABLE events (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    organization_id       BIGINT       NOT NULL,
    title                 VARCHAR(200) NOT NULL,
    description           TEXT,
    location              VARCHAR(255) NOT NULL,
    category              VARCHAR(20)  NOT NULL,
    start_at              TIMESTAMPTZ  NOT NULL,
    end_at                TIMESTAMPTZ  NOT NULL,
    capacity              INTEGER      NOT NULL,
    registration_deadline TIMESTAMPTZ,
    status                VARCHAR(30)  NOT NULL DEFAULT 'DRAFT',
    created_by            BIGINT       NOT NULL,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version               BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_events PRIMARY KEY (id),
    CONSTRAINT fk_events_organization FOREIGN KEY (organization_id)
        REFERENCES organizations (id) ON DELETE RESTRICT,
    CONSTRAINT fk_events_created_by FOREIGN KEY (created_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_events_capacity_positive CHECK (capacity > 0),
    CONSTRAINT ck_events_end_after_start CHECK (end_at > start_at),
    CONSTRAINT ck_events_deadline_before_start
        CHECK (registration_deadline IS NULL OR registration_deadline <= start_at),
    CONSTRAINT ck_events_category CHECK (category IN
        ('ACADEMIC', 'CAREER', 'CULTURAL', 'SOCIAL', 'SPORTS', 'VOLUNTEERING', 'WORKSHOP', 'OTHER')),
    CONSTRAINT ck_events_status CHECK (status IN
        ('DRAFT', 'PUBLISHED', 'REGISTRATION_CLOSED', 'ONGOING', 'COMPLETED', 'CANCELLED'))
);
-- Search (W3): "published events from date X", filter by organization / category.
CREATE INDEX ix_events_status_start_at ON events (status, start_at);
CREATE INDEX ix_events_start_at ON events (start_at);
CREATE INDEX ix_events_organization_id ON events (organization_id, start_at);
CREATE INDEX ix_events_category ON events (category);
CREATE INDEX ix_events_created_by ON events (created_by);

-- ---------------------------------------------------------------------------
-- registrations (W4)
-- ---------------------------------------------------------------------------
CREATE TABLE registrations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id      BIGINT      NOT NULL,
    user_id       BIGINT      NOT NULL,
    status        VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
    registered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    checked_in_at TIMESTAMPTZ,
    CONSTRAINT pk_registrations PRIMARY KEY (id),
    -- RESTRICT: an event that has registrations is never hard-deleted; it is CANCELLED instead.
    CONSTRAINT fk_registrations_event FOREIGN KEY (event_id)
        REFERENCES events (id) ON DELETE RESTRICT,
    CONSTRAINT fk_registrations_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_registrations_status CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    -- Only confirmed participants can be checked in.
    CONSTRAINT ck_registrations_checkin_confirmed
        CHECK (checked_in_at IS NULL OR status = 'CONFIRMED')
);
-- At most one CONFIRMED registration per (event, user); cancelled rows are kept as history,
-- so a user can register again after cancelling.
CREATE UNIQUE INDEX ux_registrations_confirmed_once
    ON registrations (event_id, user_id) WHERE status = 'CONFIRMED';
CREATE INDEX ix_registrations_event_status ON registrations (event_id, status);
CREATE INDEX ix_registrations_user_id ON registrations (user_id);

-- ---------------------------------------------------------------------------
-- event_tasks (W5)
-- ---------------------------------------------------------------------------
CREATE TABLE event_tasks (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id               BIGINT       NOT NULL,
    title                  VARCHAR(200) NOT NULL,
    description            TEXT,
    assignee_membership_id BIGINT,
    status                 VARCHAR(20)  NOT NULL DEFAULT 'TODO',
    due_at                 TIMESTAMPTZ,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_event_tasks PRIMARY KEY (id),
    CONSTRAINT fk_event_tasks_event FOREIGN KEY (event_id)
        REFERENCES events (id) ON DELETE CASCADE,
    -- Removing a member from the organization un-assigns their tasks.
    CONSTRAINT fk_event_tasks_assignee FOREIGN KEY (assignee_membership_id)
        REFERENCES organization_memberships (id) ON DELETE SET NULL,
    CONSTRAINT ck_event_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE'))
);
CREATE INDEX ix_event_tasks_event_id ON event_tasks (event_id);
CREATE INDEX ix_event_tasks_assignee ON event_tasks (assignee_membership_id);

-- ---------------------------------------------------------------------------
-- announcements (W5)
-- ---------------------------------------------------------------------------
CREATE TABLE announcements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id   BIGINT       NOT NULL,
    author_id  BIGINT       NOT NULL,
    title      VARCHAR(200) NOT NULL,
    body       TEXT         NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_announcements PRIMARY KEY (id),
    CONSTRAINT fk_announcements_event FOREIGN KEY (event_id)
        REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_announcements_author FOREIGN KEY (author_id)
        REFERENCES users (id) ON DELETE RESTRICT
);
CREATE INDEX ix_announcements_event_created ON announcements (event_id, created_at);
CREATE INDEX ix_announcements_author_id ON announcements (author_id);
